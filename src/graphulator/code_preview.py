"""Render the exported Python and show the result without leaving the app.

"Export Code" writes a standalone script that redraws the graph through
``graph_primitives``, and the Export Scaling parameters are calibration
constants baked into the *numbers that script contains* -- they do not
affect the canvas at all. Tuning them therefore meant a round trip out to a
notebook and back for every nudge, which is a preview loop wearing a
settings dialog's clothes.

This closes the loop: the generated script runs here and its figure appears
beside the code, so a scaling tweak is visible immediately.

The script is generated by :mod:`code_export` from the user's own graph --
it is our output, not untrusted input -- but a bug in generation must not
take the window down with it, so a failed render is caught and shown as a
traceback next to the last good picture.
"""

import io
import logging
import traceback

import matplotlib.pyplot as plt
from matplotlib.backends.backend_qtagg import FigureCanvasQTAgg
from PySide6.QtCore import Qt
from PySide6.QtGui import QFont
from PySide6.QtWidgets import (QApplication, QCheckBox, QDialog, QHBoxLayout,
                               QLabel, QPlainTextEdit, QPushButton,
                               QSplitter, QVBoxLayout, QWidget)

logger = logging.getLogger(__name__)


def render_code(code):
    """Run `code` and return ``(figure, error_text)``; one is always None.

    The script makes its own figure (``graph.draw()`` with no axes) and ends
    in ``plt.show()``, so the figure is taken from pyplot afterwards rather
    than handed in: nothing here needs to know how the script chose to draw.
    ``plt.close`` detaches it from pyplot's registry *before* it is adopted
    by a Qt canvas, or closing would take the canvas with it.
    """
    before = set(plt.get_fignums())
    real_show = plt.show
    was_interactive = plt.isinteractive()
    plt.show = lambda *args, **kwargs: None     # never pop a window
    plt.ioff()
    error = None
    try:
        exec(compile(code, '<generated graph code>', 'exec'),
             {'__name__': '__graphulator_preview__'})
    except Exception:
        error = traceback.format_exc()
    finally:
        plt.show = real_show
        if was_interactive:
            plt.ion()

    # Every figure the script made, newest last. Only one is kept; the rest
    # would otherwise pile up across refreshes, and on a failed run even
    # the last one is junk.
    made = [n for n in plt.get_fignums() if n not in before]
    keep = None if error is not None else made[-1:]
    for num in made:
        if keep and num == keep[0]:
            continue
        plt.close(num)
    if error is not None:
        return None, error
    if not made:
        return None, ("The generated code ran but drew nothing.\n\n"
                      "Expected it to create a figure (graph.draw()).")
    figure = plt.figure(made[-1])
    plt.close(made[-1])
    return figure, None


class CodePreviewWindow(QDialog):
    """The rendered output of the generated code, beside the code itself.

    Non-modal and resizable on purpose: it is meant to sit open next to the
    Export Scaling controls while they are being tuned, which is what
    `refresh` being callable from outside is for.
    """

    def __init__(self, window, parent=None):
        super().__init__(parent if parent is not None else window)
        self._window = window
        self._figure = None
        self._canvas = None
        self._code = ''

        self.setWindowTitle(f"{window.APP_NAME} — Code Output Preview")
        self.setModal(False)
        self.resize(1100, 720)

        layout = QVBoxLayout(self)

        # ---- controls -------------------------------------------------
        controls = QHBoxLayout()
        refresh_btn = QPushButton("Refresh")
        refresh_btn.setToolTip("Re-generate the code and render it again")
        refresh_btn.clicked.connect(self.refresh)
        controls.addWidget(refresh_btn)

        self.auto_check = QCheckBox("Auto-refresh")
        self.auto_check.setChecked(True)
        self.auto_check.setToolTip(
            "Re-render whenever the graph or an export scaling parameter "
            "changes while this window is open")
        controls.addWidget(self.auto_check)

        self.compact_check = QCheckBox("Compact (grouped by style)")
        self.compact_check.setToolTip(
            "Preview the compact export shape -- look-alike objects grouped "
            "under named style dicts -- instead of one call per object")
        self.compact_check.toggled.connect(lambda _checked: self.refresh())
        controls.addWidget(self.compact_check)

        controls.addStretch(1)

        copy_btn = QPushButton("Copy Code")
        copy_btn.setToolTip("Copy the previewed script to the clipboard")
        copy_btn.clicked.connect(self._copy_code)
        controls.addWidget(copy_btn)
        layout.addLayout(controls)

        # ---- preview | code ------------------------------------------
        self._splitter = QSplitter(Qt.Orientation.Horizontal, self)

        self._canvas_holder = QWidget()
        self._canvas_layout = QVBoxLayout(self._canvas_holder)
        self._canvas_layout.setContentsMargins(0, 0, 0, 0)
        self._placeholder = QLabel("Nothing rendered yet.")
        self._placeholder.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self._placeholder.setStyleSheet("color: gray;")
        self._canvas_layout.addWidget(self._placeholder)
        self._splitter.addWidget(self._canvas_holder)

        self.code_view = QPlainTextEdit()
        self.code_view.setReadOnly(True)
        self.code_view.setLineWrapMode(QPlainTextEdit.LineWrapMode.NoWrap)
        self.code_view.setFont(QFont("Menlo", 11))
        self._splitter.addWidget(self.code_view)
        self._splitter.setSizes([660, 440])
        layout.addWidget(self._splitter, stretch=1)

        self.status = QLabel("")
        self.status.setWordWrap(True)
        layout.addWidget(self.status)

        self.refresh()

    # ---- public API ---------------------------------------------------

    def refresh(self):
        """Re-generate the script, render it, and show both."""
        from . import code_export

        code = code_export.build_code(
            self._window, compact=self.compact_check.isChecked())
        if code is None:
            self._code = ''
            self.code_view.setPlainText('')
            self._show_figure(None)
            self._set_status("Nothing to preview — the graph is empty.",
                             error=False)
            return

        self._code = code
        self.code_view.setPlainText(code)
        figure, error = render_code(code)
        if error is not None:
            # Keep the last good picture up: the traceback says what broke,
            # and having the previous render to compare against is more
            # use than a blank panel.
            logger.warning("Code preview failed to render:\n%s", error)
            self.code_view.setPlainText(f"{error}\n\n{'-' * 60}\n\n{code}")
            self._set_status("Render failed — traceback above the code.",
                             error=True)
            return

        self._show_figure(figure)
        shape = "compact" if self.compact_check.isChecked() else "verbose"
        width, height = figure.get_size_inches()
        self._set_status(
            f"Rendered the {shape} export · {len(code.splitlines())} lines "
            f"· {width:.0f} × {height:.0f} in figure", error=False)

    def maybe_auto_refresh(self):
        """Re-render if the window is up and auto-refresh is on.

        The caller does not have to know whether the window exists or what
        the checkbox says, which keeps the hooks in the apps to one line.
        """
        if self.isVisible() and self.auto_check.isChecked():
            self.refresh()

    # ---- internals ----------------------------------------------------

    def _set_status(self, text, error):
        self.status.setStyleSheet("color: #b00020;" if error else "color: gray;")
        self.status.setText(text)

    def _show_figure(self, figure):
        """Swap in `figure`, dropping whatever was there before."""
        for widget in (self._canvas, self._placeholder):
            if widget is not None:
                self._canvas_layout.removeWidget(widget)
                widget.setParent(None)
        self._canvas = None
        self._placeholder = None

        if self._figure is not None and self._figure is not figure:
            # Released explicitly: it is no longer in pyplot's registry, so
            # nothing else would ever let go of it.
            self._figure.clear()
        self._figure = figure

        if figure is None:
            self._placeholder = QLabel("Nothing rendered yet.")
            self._placeholder.setAlignment(Qt.AlignmentFlag.AlignCenter)
            self._placeholder.setStyleSheet("color: gray;")
            self._canvas_layout.addWidget(self._placeholder)
            return

        self._canvas = FigureCanvasQTAgg(figure)
        self._canvas_layout.addWidget(self._canvas)
        self._canvas.draw_idle()

    def _copy_code(self):
        if not self._code:
            self._set_status("Nothing to copy.", error=False)
            return
        QApplication.clipboard().setText(self._code)
        self._set_status(f"Copied {len(self._code.splitlines())} lines to "
                         "the clipboard.", error=False)

    def closeEvent(self, event):
        self._show_figure(None)
        super().closeEvent(event)


def preview_png_bytes(window, compact=False):
    """The previewed render as PNG bytes, for tests and scripted checks.

    Same path the window uses, minus the Qt: generate, run, rasterize.
    Returns ``(png_bytes, error_text)``.
    """
    from . import code_export

    code = code_export.build_code(window, compact=compact)
    if code is None:
        return None, "Nothing to preview — the graph is empty."
    figure, error = render_code(code)
    if error is not None:
        return None, error
    buffer = io.BytesIO()
    figure.savefig(buffer, format='png', dpi=72)
    figure.clear()
    return buffer.getvalue(), None
